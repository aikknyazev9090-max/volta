import type { SportId, Team } from './sports/types.js';

export interface League {
  id: string;
  sport: SportId;
  name: string;
  country: string; // код страны для флага или 'world'/'eu'
  weight: number; // вероятность выбора
  teams: Team[];
}

type T = [name: string, short: string, c1: string, c2: string, rating: number];

const mk = (league: string, list: T[]): Team[] =>
  list.map(([name, short, c1, c2, rating], i) => ({ id: `${league}-${i}`, name, short, colors: [c1, c2], rating }));

const L = (id: string, sport: SportId, name: string, country: string, weight: number, list: T[]): League => ({
  id,
  sport,
  name,
  country,
  weight,
  teams: mk(id, list),
});

